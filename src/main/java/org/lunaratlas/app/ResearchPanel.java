package org.lunaratlas.app;

import org.lunaratlas.research.ResearchRecord;

import javax.swing.BorderFactory;
import javax.swing.DefaultListModel;
import javax.swing.JLabel;
import javax.swing.JList;
import javax.swing.JPanel;
import javax.swing.JScrollPane;
import javax.swing.JTextArea;
import javax.swing.JTextField;
import javax.swing.ListSelectionModel;
import java.awt.BorderLayout;
import java.awt.Font;
import java.util.List;
import java.util.Locale;

final class ResearchPanel extends JPanel {
    private final List<ResearchRecord> records;
    private final DefaultListModel<ResearchRecord> listModel = new DefaultListModel<>();
    private final JTextArea detail = new JTextArea();
    private final JTextField search = new JTextField(28);

    ResearchPanel(List<ResearchRecord> records) {
        super(new BorderLayout(12, 12));
        this.records = records;
        setBorder(BorderFactory.createEmptyBorder(16, 20, 20, 20));
        JPanel top = new JPanel(new BorderLayout(10, 4));
        top.setBackground(UiTheme.BACKGROUND);
        top.add(new JLabel("Search documented cultural records, historical observations, and evidence notes"),
                BorderLayout.NORTH);
        top.add(search, BorderLayout.CENTER);
        JLabel notice = new JLabel("Curated sample · traditions are context-specific · source quality and limits are shown");
        notice.setForeground(UiTheme.MUTED);
        top.add(notice, BorderLayout.SOUTH);
        add(top, BorderLayout.NORTH);

        JList<ResearchRecord> list = new JList<>(listModel);
        list.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        list.setCellRenderer((listView, record, index, selected, focused) -> {
            JLabel label = new JLabel("<html><b>" + escape(record.title()) + "</b><br><span style='color:#9CAFC2'>"
                    + escape(record.region()) + " · " + escape(record.kind()) + "</span></html>");
            label.setOpaque(true);
            label.setBackground(selected ? new java.awt.Color(46, 77, 104) : UiTheme.PANEL);
            label.setForeground(UiTheme.TEXT);
            label.setBorder(BorderFactory.createEmptyBorder(8, 8, 8, 8));
            return label;
        });
        list.addListSelectionListener(event -> {
            if (!event.getValueIsAdjusting()) {
                ResearchRecord selected = list.getSelectedValue();
                if (selected != null) showRecord(selected);
            }
        });
        detail.setEditable(false);
        detail.setLineWrap(true);
        detail.setWrapStyleWord(true);
        detail.setFont(detail.getFont().deriveFont(Font.PLAIN, 14f));
        detail.setBorder(BorderFactory.createEmptyBorder(16, 16, 16, 16));
        JPanel split = new JPanel(new BorderLayout(12, 0));
        split.setBackground(UiTheme.BACKGROUND);
        split.add(new JScrollPane(list), BorderLayout.WEST);
        split.add(new JScrollPane(detail), BorderLayout.CENTER);
        add(split, BorderLayout.CENTER);
        search.getDocument().addDocumentListener(new javax.swing.event.DocumentListener() {
            @Override
            public void insertUpdate(javax.swing.event.DocumentEvent event) { filter(); }
            @Override
            public void removeUpdate(javax.swing.event.DocumentEvent event) { filter(); }
            @Override
            public void changedUpdate(javax.swing.event.DocumentEvent event) { filter(); }
        });
        filter();
        if (!listModel.isEmpty()) list.setSelectedIndex(0);
    }

    private void filter() {
        String query = search.getText().trim().toLowerCase(Locale.ROOT);
        listModel.clear();
        for (ResearchRecord record : records) {
            String haystack = (record.kind() + " " + record.region() + " " + record.title() + " "
                    + record.description() + " " + record.period() + " " + record.category()
                    + " " + record.source()).toLowerCase(Locale.ROOT);
            if (haystack.contains(query)) listModel.addElement(record);
        }
        if (listModel.isEmpty()) {
            detail.setText("No bundled record matches this search. The atlas is a small, sourced sample, not a complete survey.");
        }
    }

    private void showRecord(ResearchRecord record) {
        detail.setText(record.title() + "\n" + record.region() + " · " + record.category()
                + (record.period().isBlank() ? "" : " · " + record.period())
                + "\n\n" + record.description() + "\n\nSource: " + record.source()
                + "\n\nConfidence / scope: " + record.confidence()
                + "\n\nClassification: " + record.kind().toUpperCase(Locale.ROOT)
                + " (curated record; not an observation generated by this application).");
        detail.setCaretPosition(0);
    }

    private static String escape(String text) {
        return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;");
    }
}
